def render_markdown_to_pdf(
    md_content: str,
    output_path: Path,
    doc_title: str | None = None,
) -> Path:
    """Convert Markdown into a styled PDF document."""

    output_path = Path(
        output_path
    )

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    doc = SimpleDocTemplate(
        str(output_path),
        pagesize=letter,
        leftMargin=36,
        rightMargin=36,
        topMargin=60,
        bottomMargin=60,
        allowSplitting=1,
    )

    styles = _build_styles()

    flowables = parse_markdown_to_flowables(
        md_content,
        styles,
    )

    doc.build(
        flowables,
        canvasmaker=FlowScopeCanvas,
    )

    return output_path


# ---------------------------------------------------------------------------
# File rendering
# ---------------------------------------------------------------------------

def render_pdf_file(
    input_path: Path,
    output_path: Path,
) -> Path:
    """Read Markdown or blocks JSON and convert it into a PDF."""

    input_path = Path(
        input_path
    )

    if not input_path.exists():

        raise FileNotFoundError(
            f"Input file not found: {input_path}"
        )

    content = input_path.read_text(
        encoding="utf-8"
    )

    # If input is blocks JSON, convert using
    # flowscope_markdown when available.
    if input_path.suffix == ".json":

        try:

            import flowscope_markdown

            content = (
                flowscope_markdown.render_markdown(
                    input_path
                )
            )

        except Exception:
            pass

    return render_markdown_to_pdf(
        content,
        output_path,
    )


# ---------------------------------------------------------------------------
# CLI
