# Markdown formatting
# ---------------------------------------------------------------------------

def _clean_inline_markdown(text: str) -> str:
    """Convert Markdown inline styles to ReportLab XML."""

    # Escape XML special characters first.
    text = (
        text
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )

    # Bold.
    text = re.sub(
        r"\*\*(.*?)\*\*",
        r'<b><font color="#7c3aed">\1</font></b>',
        text,
    )

    # Italic.
    text = re.sub(
        r"\*(.*?)\*",
        r'<i><font color="#a855f7">\1</font></i>',
        text,
    )

    # Inline code.
    text = re.sub(
        r"`(.*?)`",
        r'<font name="Courier" color="#6b21a8" size="9"><b>\1</b></font>',
        text,
    )

    return text


def _format_header_badges(
    text: str,
) -> str:
    """Format category tags like [SETUP], [CONFIG]."""

    badge_colors = {
        "SETUP": "#db2777",
        "DEPENDENCY": "#a855f7",
        "CONFIG": "#c084fc",
        "BUILD": "#f472b6",
        "EXECUTION": "#7c3aed",
        "VERIFICATION": "#ec4899",
        "CLEANUP": "#9370db",
    }

    def replace_badge(match):

        tag = match.group(1).upper()

        color = badge_colors.get(
            tag,
            "#a855f7",
        )

        return (
            f' <font color="{color}">'
            f'<b>[{tag}]</b>'
            f'</font>'
        )

    return re.sub(
        r"\[([A-Za-z0-9_-]+)\]",
        replace_badge,
        text,
    )


