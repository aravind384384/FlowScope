def main() -> None:

    if len(sys.argv) < 2:

        sys.exit(
            f"Usage: {sys.argv[0]} "
            "<input.md|blocks.json> "
            "[--out output.pdf]"
        )

    input_path = Path(
        sys.argv[1]
    )

    out_path = input_path.with_suffix(
        ".pdf"
    )

    if (
        "--out" in sys.argv
        or "-o" in sys.argv
    ):

        idx = (
            sys.argv.index("--out")
            if "--out" in sys.argv
            else sys.argv.index("-o")
        )

        out_path = Path(
            sys.argv[idx + 1]
        )

    result = render_pdf_file(
        input_path,
        out_path,
    )

    print(
        f"PDF guide successfully generated at: {result}"
    )


if __name__ == "__main__":
    main()