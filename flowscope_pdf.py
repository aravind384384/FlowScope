def _escape_code_line(text: str) -> str:
    """Escape terminal text for ReportLab XML while preserving indentation."""

    text = (
        text
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )

    # Preserve leading spaces.
    leading = len(text) - len(text.lstrip(" "))

    if leading:
        text = (
            ("&#160;" * leading)
            + text[leading:]
        )

    return text


def _build_wrapped_code_table(
    code_text: str,
    styles: dict[str, ParagraphStyle],
) -> Table:
    """
    Build a code-output box that wraps long terminal lines
    without adding extra vertical spacing between lines.
    """

    raw_lines = code_text.split("\n")

    rows = []

    for line in raw_lines:

        if line == "":
            paragraph = Paragraph(
                "&#160;",
                styles["Code"],
            )
        else:
            escaped = _escape_code_line(line)

            paragraph = Paragraph(
                escaped,
                styles["Code"],
            )

        rows.append([paragraph])

    table_width = 540

    table = Table(
        rows,
        colWidths=[table_width],
        repeatRows=0,
        splitByRow=1,
        hAlign="LEFT",
    )

    # No vertical padding between individual lines.
    # Only the first and last rows get outer spacing.
    table.setStyle(
        TableStyle(
            [
                (
                    "BACKGROUND",
                    (0, 0),
                    (-1, -1),
                    colors.HexColor("#faf5ff"),
                ),

                (
                    "BOX",
                    (0, 0),
                    (-1, -1),
                    2,
                    colors.HexColor("#c084fc"),
                ),

                (
                    "LEFTPADDING",
                    (0, 0),
                    (-1, -1),
                    12,
                ),

                (
                    "RIGHTPADDING",
                    (0, 0),
                    (-1, -1),
                    12,
                ),

                # Remove extra vertical space between lines.
                (
                    "TOPPADDING",
                    (0, 0),
                    (-1, -1),
                    0,
                ),

                (
                    "BOTTOMPADDING",
                    (0, 0),
                    (-1, -1),
                    0,
                ),

                # Small padding at the top of the box.
                (
                    "TOPPADDING",
                    (0, 0),
                    (-1, 0),
                    6,
                ),

                # Small padding at the bottom of the box.
                (
                    "BOTTOMPADDING",
                    (0, -1),
                    (-1, -1),
                    6,
                ),

                (
                    "VALIGN",
                    (0, 0),
                    (-1, -1),
                    "TOP",
                ),
            ]
        )
    )

    return table
