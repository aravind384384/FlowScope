class FlowScopeCanvas(canvas.Canvas):
    """Enhanced canvas with FlowScope branding, headers, footers, and page decoration."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decoration(num_pages)
            super().showPage()
        super().save()

    def draw_page_decoration(self, page_count: int):
        """Draws FlowScope-branded headers, footers, and decorative elements."""
        self.saveState()
        
        # Page-specific header decoration
        if self._pageNumber == 1:
            # First page: decorative top accent
            self.setStrokeColor(colors.HexColor("#ec4899"))  # Cupid Pink
            self.setLineWidth(2.5)
            self.line(36, 772, 576, 772)
        else:
            # Subsequent pages: header with FlowScope branding
            self.setFont("Helvetica-Bold", 8)
            self.setFillColor(colors.HexColor("#c084fc"))  # Cupid Purple
            self.drawString(36, 762, "⟡ FlowScope Terminal Guide")
            
            # Header accent line
            self.setStrokeColor(colors.HexColor("#c084fc"))
            self.setLineWidth(1.5)
            self.line(36, 758, 576, 758)

        # Footer section (all pages)
        self.setStrokeColor(colors.HexColor("#ddd6fe"))  # Light purple border
        self.setLineWidth(1.5)
        self.line(36, 48, 576, 48)

        # Footer text
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#9370db"))  # Cupid Purple (muted)

        footer_text = "Generated by FlowScope"
        page_str = f"Page {self._pageNumber} of {page_count}"
        
        self.drawString(36, 33, footer_text)
        self.drawRightString(576, 33, page_str)

        # Decorative dots
        self.setFillColor(colors.HexColor("#fce7f3"))  # Cupid Pink (very light)
        for i in range(3):
            x = 300 + (i * 12) - 12
            self.circle(x, 27, 1.5, fill=1)

        self.restoreState()


