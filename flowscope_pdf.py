def parse_markdown_to_flowables(
    md_content: str,
    styles: dict[str, ParagraphStyle],
) -> list:
    """Parse Markdown into ReportLab flowables."""

    flowables = []

    lines = md_content.splitlines()

    i = 0

    in_code_block = False
    code_lines = []
    code_lang = ""

    while i < len(lines):

        line = lines[i]

        # ---------------------------------------------------------------
        # Code block
        # ---------------------------------------------------------------

        if line.strip().startswith("```"):

            if not in_code_block:

                in_code_block = True

                code_lang = (
                    line.strip()
                    .lstrip("`")
                    .strip()
                )

                code_lines = []

            else:

                in_code_block = False

                code_text = "\n".join(
                    code_lines
                )

                if code_text:

                    flowables.append(
                        Spacer(
                            1,
                            6,
                        )
                    )

                    # ---------------------------------------------------
                    # FIX:
                    # Use wrapped table instead of Preformatted.
                    # ---------------------------------------------------

                    code_table = (
                        _build_wrapped_code_table(
                            code_text,
                            styles,
                        )
                    )

                    flowables.append(
                        code_table
                    )

                    flowables.append(
                        Spacer(
                            1,
                            10,
                        )
                    )

            i += 1
            continue

        if in_code_block:

            code_lines.append(line)

            i += 1
            continue

        stripped = line.strip()

        # ---------------------------------------------------------------
        # Empty line
        # ---------------------------------------------------------------

        if not stripped:

            i += 1
            continue

        # ---------------------------------------------------------------
        # Horizontal rule
        # ---------------------------------------------------------------

        if stripped in (
            "---",
            "***",
            "___",
        ):

            flowables.append(
                Spacer(
                    1,
                    6,
                )
            )

            flowables.append(
                HRFlowable(
                    width="100%",
                    thickness=1.5,
                    color=colors.HexColor("#e9d5ff"),
                    spaceBefore=8,
                    spaceAfter=12,
                )
            )

            i += 1
            continue

        # ---------------------------------------------------------------
        # H1
        # ---------------------------------------------------------------

        if stripped.startswith("# "):

            title_text = _clean_inline_markdown(
                stripped[2:]
            )

            flowables.append(
                Spacer(
                    1,
                    4,
                )
            )

            flowables.append(
                Paragraph(
                    title_text,
                    styles["Title"],
                )
            )

            flowables.append(
                Spacer(
                    1,
                    2,
                )
            )

            hr1 = HRFlowable(
                width="100%",
                thickness=3,
                color=colors.HexColor("#ec4899"),
                spaceBefore=0,
                spaceAfter=2,
            )

            hr2 = HRFlowable(
                width="100%",
                thickness=1.5,
                color=colors.HexColor("#c084fc"),
                spaceBefore=0,
                spaceAfter=12,
            )

            flowables.append(hr1)
            flowables.append(hr2)

            i += 1
            continue

        # ---------------------------------------------------------------
        # H2
        # ---------------------------------------------------------------

        elif stripped.startswith("## "):

            h2_text = _clean_inline_markdown(
                stripped[3:]
            )

            h2_html = _format_header_badges(
                h2_text
            )

            flowables.append(
                Spacer(
                    1,
                    2,
                )
            )

            flowables.append(
                Paragraph(
                    h2_html,
                    styles["H2"],
                )
            )

            flowables.append(
                Spacer(
                    1,
                    1,
                )
            )

            i += 1
            continue

        # ---------------------------------------------------------------
        # H3
        # ---------------------------------------------------------------

        elif stripped.startswith("### "):

            h3_text = _clean_inline_markdown(
                stripped[4:]
            )

            flowables.append(
                Paragraph(
                    h3_text,
                    styles["H3"],
                )
            )

            flowables.append(
                Spacer(
                    1,
                    1,
                )
            )

            i += 1
            continue

        # ---------------------------------------------------------------
        # Bullet list
        # ---------------------------------------------------------------

        if (
            stripped.startswith("- ")
            or stripped.startswith("* ")
        ):

            item_text = _clean_inline_markdown(
                stripped[2:]
            )

            flowables.append(
                Paragraph(
                    f"◆ {item_text}",
                    styles["Bullet"],
                )
            )

            i += 1
            continue

        # ---------------------------------------------------------------
        # Callout / Quote / Expected Output
        # ---------------------------------------------------------------

        if (
            stripped.startswith("*Expected Output:*")
            or stripped.startswith("> ")
        ):

            callout_text = (
                _clean_inline_markdown(
                    stripped.lstrip("> ").strip()
                )
            )

            paragraph = Paragraph(
                callout_text,
                styles["Callout"],
            )

            table = Table(
                [[paragraph]],
                colWidths=[540],
            )

            table.setStyle(
                TableStyle(
                    [
                        (
                            "BACKGROUND",
                            (0, 0),
                            (-1, -1),
                            colors.HexColor("#fce7f3"),
                        ),

                        (
                            "LINELEFT",
                            (0, 0),
                            (0, 0),
                            4,
                            colors.HexColor("#ec4899"),
                        ),

                        (
                            "LEFTPADDING",
                            (0, 0),
                            (-1, -1),
                            12,
                        ),

                        (
                            "RIGHTPADDING",
                            (0, 0),
                            (-1, -1),
                            12,
                        ),

                        (
                            "TOPPADDING",
                            (0, 0),
                            (-1, -1),
                            8,
                        ),

                        (
                            "BOTTOMPADDING",
                            (0, 0),
                            (-1, -1),
                            8,
                        ),
                    ]
                )
            )

            flowables.append(
                Spacer(
                    1,
                    6,
                )
            )

            flowables.append(table)

            flowables.append(
                Spacer(
                    1,
                    8,
                )
            )

            i += 1
            continue

        # ---------------------------------------------------------------
        # Normal paragraph
        # ---------------------------------------------------------------

        para_text = _clean_inline_markdown(
            stripped
        )

        flowables.append(
            Paragraph(
                para_text,
                styles["Body"],
            )
        )

        i += 1

    return flowables


