class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and print total page count and header/footer."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            super().showPage()
        super().save()

    def draw_page_number(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#64748b"))  # Slate grey

        # Top Header (pages 2+)
        if self._pageNumber > 1:
            self.drawString(36, 756, "FlowScope Technical Guide")
            self.setStrokeColor(colors.HexColor("#cbd5e1"))
            self.setLineWidth(0.5)
            self.line(36, 750, 576, 750)

        # Bottom Footer (all pages)
        self.setStrokeColor(colors.HexColor("#cbd5e1"))
        self.setLineWidth(0.5)
        self.line(36, 45, 576, 45)

        footer_text = "Generated by FlowScope"
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawString(36, 30, footer_text)
        self.drawRightString(576, 30, page_str)

        self.restoreState()


